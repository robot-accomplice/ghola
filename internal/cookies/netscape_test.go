package cookies

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// curlJar is the exact jar that curl 8.18.0 wrote (curl -c) on 2026-11-20
// for a local server that set a host-only cookie and a Secure HttpOnly
// cookie with Max-Age. curl writes CRLF line ends on Windows.
const curlJar = "# Netscape HTTP Cookie File\r\n# https://curl.se/docs/http-cookies.html\r\n# This file was generated by libcurl! Edit at your own risk.\r\n\r\n" +
	"#HttpOnly_127.0.0.1\tFALSE\t/\tTRUE\t1795166719\tsec\t3\r\n" +
	"127.0.0.1\tFALSE\t/\tFALSE\t0\thostonly\t1\r\n"

// ghola reads curl's jar: the fields, the #HttpOnly_ prefix, a session
// cookie (expiry 0) and the host-only flag.
func TestNetscape_ReadsCurlJar(t *testing.T) {
	path := filepath.Join(t.TempDir(), "jar.txt")
	os.WriteFile(path, []byte(curlJar), 0o644) //nolint:errcheck
	j, err := New(path)
	if err != nil {
		t.Fatal(err)
	}
	if len(j.entries) != 2 {
		t.Fatalf("%d entries, want 2", len(j.entries))
	}
	sec, host := j.entries[0], j.entries[1]
	if !sec.HTTPOnly || !sec.Secure || !sec.HostOnly || sec.Expires == nil || sec.Expires.Unix() != 1795166719 {
		t.Errorf("sec = %+v", sec)
	}
	if host.Expires != nil || !host.HostOnly || host.Name != "hostonly" || host.Value != "1" {
		t.Errorf("hostonly = %+v", host)
	}
	if got := j.HeaderValue("http://127.0.0.1/"); got != "hostonly=1" {
		t.Errorf("http gets %q, want only the cookie that is not Secure", got)
	}
}

// A new jar is written in the Netscape format, and a domain cookie keeps
// its leading dot and TRUE, as curl writes it.
func TestNetscape_WritesANewJar(t *testing.T) {
	path := filepath.Join(t.TempDir(), "jar.txt")
	j, _ := New(path)
	setCookie(t, j, "https://www.example.com/", "a=1; Domain=example.com", "b=2")
	if err := j.Save(); err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(path)
	text := string(b)
	for _, want := range []string{"# Netscape HTTP Cookie File", ".example.com\tTRUE\t/\tFALSE\t0\ta\t1", "www.example.com\tFALSE\t/\tFALSE\t0\tb\t2"} {
		if !strings.Contains(text, want) {
			t.Errorf("jar lacks %q:\n%s", want, text)
		}
	}
	again, err := New(path)
	if err != nil || again.HeaderValue("https://api.example.com/") != "a=1" {
		t.Errorf("the written jar does not read back: %v", err)
	}
}

// A v0 JSON jar is read, and written back as JSON, so a v0 user's jar keeps
// working with the same file.
func TestJar_V0JSONStaysJSON(t *testing.T) {
	path := filepath.Join(t.TempDir(), "jar.json")
	os.WriteFile(path, []byte(`[{"name":"tok","value":"abc","domain":"example.com","path":"/"}]`), 0o644) //nolint:errcheck
	j, _ := New(path)
	if err := j.Save(); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(path); !strings.HasPrefix(strings.TrimSpace(string(b)), "[") {
		t.Errorf("the v0 jar was rewritten in another format:\n%s", b)
	}
}

// A line with the wrong number of fields is an error that names the line,
// so a broken jar does not lose cookies without a word.
func TestNetscape_BadLine(t *testing.T) {
	path := filepath.Join(t.TempDir(), "jar.txt")
	os.WriteFile(path, []byte("example.com\tFALSE\t/\n"), 0o644) //nolint:errcheck
	if _, err := New(path); err == nil || !strings.Contains(err.Error(), "line 1") {
		t.Fatalf("err = %v", err)
	}
}
